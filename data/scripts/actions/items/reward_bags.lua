local grandChanceByBurden = { [1] = 10, [2] = 20, [3] = 35, [4] = 50 }

local randomItems = Action()

function randomItems.onUse(player, item, fromPosition, target, toPosition, isHotkey)
	-- Use the server-side id accessor.  It is reliable for items in a corpse,
	-- container, inventory or on the ground.
	local bagId = item:getId()
	local rewardBag = rewardBags[bagId]
	if not rewardBag then
		return false
	end

	local burdenStage = item:getCustomAttribute("bakragore-burden-stage") or 0
	if bagId == BAG_YOU_COVET and (grandChanceByBurden[burdenStage] or 0) > 0 and math.random(100) <= grandChanceByBurden[burdenStage] then
		rewardBag = grandSanguineRewards
	end

	local randomIndex = math.random(1, #rewardBag)
	local rewardItem = rewardBag[randomIndex]
	local receivedItem = player:addItem(rewardItem.id, 1)
	if not receivedItem then
		player:sendTextMessage(MESSAGE_STATUS_SMALL, "You need a free slot or enough capacity to open this bag.")
		return true
	end

	logger.info("[RewardBag] {} opened bag {} and received {}", player:getName(), bagId, rewardItem.name)
	player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "You received a " .. rewardItem.name .. ".")
	if taskStoreChests[bagId] then
		player:getPosition():sendMagicEffect(244)
		player:setItemOutfit(rewardItem.id, TASK_STORE_TRANSFORMATION_DURATION)
	end

	local text = player:getName() .. " received a " .. rewardItem.name .. " from a " .. item:getName() .. "."
	Webhook.sendMessage(":game_die: " .. player:getMarkdownLink() .. " received a **" .. rewardItem.name .. "** from a _" .. item:getName() .. "_.")
	Broadcast(text, function(targetPlayer)
		return targetPlayer ~= player
	end)

	item:remove(1)
	return true
end

for itemId, info in pairs(rewardBags) do
	randomItems:id(tonumber(itemId))
end

randomItems:register()
